//! Portable regression for commands that compile but are unreachable through
//! Tauri IPC because their manifest declaration or capability was omitted.
use std::{collections::BTreeSet, fs, path::Path};

fn commands(source: &str) -> BTreeSet<String> {
    source
        .split("#[tauri::command]")
        .skip(1)
        .map(|definition| {
            definition
                .split_once("fn ")
                .unwrap()
                .1
                .split_once('(')
                .unwrap()
                .0
                .trim()
                .to_owned()
        })
        .collect()
}

fn handlers(source: &str) -> BTreeSet<String> {
    let block = source
        .split_once("tauri::generate_handler![")
        .unwrap()
        .1
        .split_once(']')
        .unwrap()
        .0;
    block
        .split(',')
        .map(str::trim)
        .filter(|name| !name.is_empty())
        .map(str::to_owned)
        .collect()
}

#[test]
fn every_desktop_command_has_a_handler_manifest_and_enabled_permission() {
    let sources = [
        include_str!("../src/desktop/form.rs"),
        include_str!("../src/desktop/agent.rs"),
    ];
    let mut declared = BTreeSet::new();
    for source in sources {
        let definitions = commands(source);
        assert_eq!(
            definitions,
            handlers(source),
            "every command must have a matching invoke handler"
        );
        declared.extend(definitions);
    }
    let manifest = include_str!("../build.rs")
        .split_once(".commands(&[")
        .unwrap()
        .1
        .split_once(']')
        .unwrap()
        .0;
    let manifest: BTreeSet<_> = manifest
        .split(',')
        .map(str::trim)
        .filter(|name| !name.is_empty())
        .map(|name| name.trim_matches('"').to_owned())
        .collect();
    assert_eq!(
        manifest, declared,
        "the AppManifest must declare every registered command"
    );
    assert!(declared.contains("agent_start_named_task"));

    let capability: serde_json::Value =
        serde_json::from_str(include_str!("../capabilities/bridge.json")).unwrap();
    assert_eq!(capability["windows"], serde_json::json!(["main"]));
    assert!(capability.get("remote").is_none());
    let permissions: BTreeSet<_> = capability["permissions"]
        .as_array()
        .unwrap()
        .iter()
        .map(|value| value.as_str().unwrap().to_owned())
        .filter(|value| value != "core:default")
        .collect();
    let expected: BTreeSet<_> = declared
        .iter()
        .map(|command| format!("allow-{}", command.replace('_', "-")))
        .collect();
    assert_eq!(
        permissions, expected,
        "the bundled main page must be allowed to invoke each command"
    );
    for command in declared {
        let permission = fs::read_to_string(
            Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("permissions/autogenerated")
                .join(format!("{command}.toml")),
        )
        .unwrap();
        let slug = command.replace('_', "-");
        assert!(permission.contains(&format!("identifier = \"allow-{slug}\"")));
        assert!(permission.contains(&format!("commands.allow = [\"{command}\"]")));
        assert!(permission.contains(&format!("identifier = \"deny-{slug}\"")));
        assert!(permission.contains(&format!("commands.deny = [\"{command}\"]")));
    }
}
